#!/usr/bin/env python3
"""ssh-1password: use the 1Password SSH agent with one key per trust domain and one alias per host.

Private keys stay in 1Password; only public keys (.pub) are written to disk. Your own ~/.ssh/config
is left alone except for one Include line at the end, so anything you wrote above it wins.

Usage: ssh-1password.py install|doctor [--dry-run] [--file <hosts.yml>] [--home <dir>]
  install    copy the registry template if missing, fetch public keys from the agent, write
             ~/.ssh/config.d/1password.conf, include it from ~/.ssh/config, keep agent.toml in sync
  doctor     check the setup on this machine; exits 1 on any FAIL
  --dry-run  show what install would write without touching anything
  --file     registry path (default: $SSH_1P_HOSTS or ~/.config/ssh-1password/hosts.yml)
  --home     treat this directory as the home directory (tests, inspection)

Registry format (flat YAML, PyYAML optional):
  github-work:                  # alias: what you type after "ssh" and in git remotes
    hostname: github.com        # optional
    user: git                   # optional; SSH login, always "git" on GitHub/GitLab (not your account)
    port: 22                    # optional
    key: GitHub work            # required: title of the SSH key item in 1Password, or SHA256:fingerprint
    vault: Work                 # optional: only for keys outside the Personal/Private/Employee vaults
    email: me@work.example      # optional: git identity for repos whose remote uses this alias
    name: My Name               # optional, with email
    sign: manual                # optional, with email: always | manual (SSH commit signing via 1Password)
    signing_key: Signing work   # optional, with sign: a dedicated 1Password key item (default: key)

Git identity: for each host with email, install writes ~/.config/ssh-1password/git/<alias>.gitconfig
and global `includeIf "hasconfig:remote.*.url:<user>@<alias>:*/**"` entries (git 2.36+), so commits in repos
cloned through that alias use that email/name without per-repo configuration.

Commit signing: with sign, the same file also sets gpg.format=ssh, 1Password's op-ssh-sign as the
signing program, user.signingkey (the public key line) and an allowed_signers file for verification.
`always` turns commit.gpgsign/tag.gpgsign on; `manual` leaves signing to `git commit -S` or to a
per-repository `commit.gpgsign true`. Upload the .pub to GitHub/GitLab as a "Signing key" yourself.

Python 3.8+, standard library only. Never run it from an AI agent session: it writes under ~/.ssh.
"""
import base64
import fnmatch
import hashlib
import os
import re
import shutil
import stat
import subprocess
import sys
import time

GENERATED_MARK = "# generated by ssh-1password.py"
CONF_REL = "config.d/1password.conf"          # relative to ~/.ssh, as ssh resolves Include
PUB_DIR_REL = "1password"                      # ~/.ssh/1password/<slug>.pub
INCLUDE_BLOCK = (
    "\n# ssh-1password: kept last so that your own Host blocks above win (first value found is used)\n"
    "Match all\n"
    f"Include {CONF_REL}\n"
)
SSH_ADD = ["ssh-add", "-L"]                    # tests replace this with a fake
SSH_ADD_TIMEOUT = 120                          # seconds: 1Password may be waiting for an unlock
PLATFORM = sys.platform

ROOT = os.path.dirname(os.path.abspath(__file__))
TEMPLATE = os.path.join(ROOT, "templates", "hosts.yml")


# --- environment -----------------------------------------------------------------------------

class Env:
    def __init__(self, home, registry=None, dry=False):
        self.home = os.path.abspath(home)
        self.real_home = os.path.realpath(self.home) == os.path.realpath(os.path.expanduser("~"))
        self.dry = dry
        self.ssh_dir = os.path.join(self.home, ".ssh")
        self.config = os.path.join(self.ssh_dir, "config")
        self.conf = os.path.join(self.ssh_dir, CONF_REL)
        self.pub_dir = os.path.join(self.ssh_dir, PUB_DIR_REL)
        xdg = os.environ.get("XDG_CONFIG_HOME") if self.real_home else None
        config_home = xdg or os.path.join(self.home, ".config")
        self.registry = registry or (os.environ.get("SSH_1P_HOSTS") if self.real_home else None) \
            or os.path.join(config_home, "ssh-1password", "hosts.yml")
        self.agent_toml = os.path.join(config_home, "1Password", "ssh", "agent.toml")
        self.git_dir = os.path.join(config_home, "ssh-1password", "git")
        self.allowed_signers = os.path.join(config_home, "ssh-1password", "allowed_signers")
        if PLATFORM == "darwin":
            self.sock_tilde = "~/Library/Group Containers/2BUA8C4S2C.com.1password/t/agent.sock"
        else:
            self.sock_tilde = "~/.1password/agent.sock"
        self.sock = os.path.join(self.home, self.sock_tilde[2:])

    def tilde(self, path):
        """Portable spelling of a path under home (the generated files must work on any machine)."""
        return "~" + path[len(self.home):] if path.startswith(self.home + os.sep) else path


def app_installed():
    if PLATFORM == "darwin":
        return any(os.path.isdir(p) for p in ("/Applications/1Password.app",
                                               os.path.expanduser("~/Applications/1Password.app")))
    return bool(shutil.which("1password")) or os.path.isdir("/opt/1Password")


def signer_candidates():
    if PLATFORM == "darwin":
        return ["/Applications/1Password.app/Contents/MacOS/op-ssh-sign",
                os.path.expanduser("~/Applications/1Password.app/Contents/MacOS/op-ssh-sign")]
    return ["/opt/1Password/op-ssh-sign"]


def signer_path():
    """op-ssh-sign shipped inside the 1Password app, or None. Tests replace this function."""
    for cand in signer_candidates():
        if os.path.isfile(cand):
            return cand
    return None


def say(*parts):
    print(" ".join(str(p) for p in parts))


# --- registry ---------------------------------------------------------------------------------

FIELDS = ("hostname", "user", "port", "key", "vault", "email", "name", "sign", "signing_key")
SIGN_MODES = ("always", "manual")


def _unquote(v):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
        return v[1:-1]
    return v


def _strip_comment(line):
    if line.lstrip().startswith("#"):
        return ""
    return re.split(r"\s+#", line, 1)[0].rstrip()


def parse_simple_yaml(text):
    """Two-level mapping: alias at column 0, fields indented. Enough for hosts.yml without PyYAML."""
    data, cur = {}, None
    for raw in text.splitlines():
        line = _strip_comment(raw)
        if not line.strip() or ":" not in line:
            continue
        indent = len(line) - len(line.lstrip(" "))
        k, v = line.strip().split(":", 1)
        k, v = _unquote(k), _unquote(v)
        if indent == 0:
            cur = k
            data[cur] = {}
        elif cur is not None:
            data[cur][k] = v
    return data


def load_registry(path):
    """Returns (hosts, problems). hosts: list of dicts with alias + FIELDS, in file order."""
    if not os.path.isfile(path):
        return None, [f"{path} does not exist"]
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    try:
        import yaml  # type: ignore
        raw = yaml.safe_load(text) or {}
    except Exception:
        raw = parse_simple_yaml(text)
    hosts, problems = [], []
    if not isinstance(raw, dict):
        return [], [f"{path}: expected a mapping of alias -> fields"]
    for alias, cfg in raw.items():
        alias = str(alias).strip()
        if not isinstance(cfg, dict):
            problems.append(f"{alias}: no fields (needs at least key:)")
            continue
        host = {"alias": alias}
        for f in FIELDS:
            v = cfg.get(f)
            host[f] = str(v).strip() if v is not None else ""
        unknown = sorted(set(cfg) - set(FIELDS))
        if unknown:
            problems.append(f"{alias}: unknown field(s) {', '.join(unknown)} (ignored)")
        if not host["key"]:
            problems.append(f"{alias}: missing key: (title of the 1Password item); entry skipped")
            continue
        if host["name"] and not host["email"]:
            problems.append(f"{alias}: name: without email: is ignored (git identity needs the email)")
            host["name"] = ""
        if host["sign"] and host["sign"] not in SIGN_MODES:
            problems.append(f"{alias}: sign: must be {' or '.join(SIGN_MODES)}, not '{host['sign']}'; ignored")
            host["sign"] = ""
        elif host["sign"] and not host["email"]:
            problems.append(f"{alias}: sign: without email: is ignored (commit signing needs the email)")
            host["sign"] = ""
        if host["signing_key"] and not host["sign"]:
            problems.append(f"{alias}: signing_key: without sign: is ignored")
            host["signing_key"] = ""
        hosts.append(host)
    return hosts, problems


def distinct_keys(hosts):
    """Key specs (authentication and signing) in first-seen order, each with the vault of its first mention."""
    seen = {}
    for h in hosts:
        for spec in (h["key"], h["signing_key"]):
            if not spec:
                continue
            if spec not in seen:
                seen[spec] = h["vault"]
            elif h["vault"] and not seen[spec]:
                seen[spec] = h["vault"]
    return list(seen.items())


def slug(title):
    if title.startswith("SHA256:"):
        return "fp-" + re.sub(r"[^a-z0-9]+", "", title[7:].lower())[:16]
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-") or "key"


# --- agent -------------------------------------------------------------------------------------

def fingerprint(b64_blob):
    digest = hashlib.sha256(base64.b64decode(b64_blob)).digest()
    return "SHA256:" + base64.b64encode(digest).decode().rstrip("=")


def parse_pubkeys(text):
    """Lines of `type base64 [comment]` -> list of (type, blob, comment)."""
    keys = []
    for line in text.splitlines():
        parts = line.strip().split(None, 2)
        if len(parts) >= 2 and parts[0].startswith(("ssh-", "ecdsa-", "sk-")):
            keys.append((parts[0], parts[1], parts[2] if len(parts) > 2 else ""))
    return keys


def agent_keys(env):
    """(status, keys). status: 'ok' | 'empty' | 'unreachable' | 'timeout' | 'no-ssh-add'."""
    sub_env = dict(os.environ, SSH_AUTH_SOCK=env.sock)
    try:
        r = subprocess.run(SSH_ADD, env=sub_env, capture_output=True, text=True, timeout=SSH_ADD_TIMEOUT)
    except FileNotFoundError:
        return "no-ssh-add", []
    except subprocess.TimeoutExpired:
        return "timeout", []
    if r.returncode == 0:
        return "ok", parse_pubkeys(r.stdout)
    if r.returncode == 1:
        return "empty", []
    return "unreachable", []


def match_key(spec, keys):
    if spec.startswith("SHA256:"):
        return [k for k in keys if fingerprint(k[1]) == spec]
    return [k for k in keys if k[2] == spec]


def read_pub(path):
    try:
        with open(path, encoding="utf-8") as fh:
            keys = parse_pubkeys(fh.read())
        return keys[0] if keys else None
    except OSError:
        return None


# --- rendering ---------------------------------------------------------------------------------

def render_conf(env, hosts):
    out = [f"{GENERATED_MARK} from {env.tilde(env.registry)}; do not edit by hand (re-run install)"]
    for h in hosts:
        out.append(f"\nHost {h['alias']}")
        if h["hostname"]:
            out.append(f"    HostName {h['hostname']}")
        if h["user"]:
            out.append(f"    User {h['user']}")
        if h["port"]:
            out.append(f"    Port {h['port']}")
        out.append(f"    IdentityFile ~/.ssh/{PUB_DIR_REL}/{slug(h['key'])}.pub")
        out.append("    IdentitiesOnly yes")
    out.append("\nHost *")
    out.append(f'    IdentityAgent "{env.sock_tilde}"')
    out.append("    ForwardAgent no")
    out.append("    AddKeysToAgent no")
    return "\n".join(out) + "\n"


def render_agent_toml(env, hosts):
    """agent.toml content, or None when it would hold no entry (an empty allowlist hides every key)."""
    out = [f"{GENERATED_MARK} from {env.tilde(env.registry)}; do not edit by hand (re-run install)",
           "# Only the keys listed here are offered to SSH servers, in this order."]
    entries = 0
    for spec, vault in distinct_keys(hosts):
        if spec.startswith("SHA256:"):
            continue  # agent.toml matches by item title or id, not by fingerprint
        out.append("\n[[ssh-keys]]")
        out.append(f'item = "{spec}"')
        if vault:
            out.append(f'vault = "{vault}"')
        entries += 1
    return "\n".join(out) + "\n" if entries else None


def is_ours(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.readline().startswith(GENERATED_MARK)
    except OSError:
        return False


def include_present(env):
    """True if ~/.ssh/config already has an Include whose pattern covers our conf file."""
    try:
        with open(env.config, encoding="utf-8") as fh:
            lines = fh.read().splitlines()
    except OSError:
        return False
    for line in lines:
        m = re.match(r"^\s*Include\s+(.+?)\s*$", line, re.IGNORECASE)
        if not m:
            continue
        for pat in m.group(1).split():
            pat = pat.strip("\"'")
            pat = os.path.join(env.home, pat[2:]) if pat.startswith("~/") else pat
            if not os.path.isabs(pat):
                pat = os.path.join(env.ssh_dir, pat)
            if fnmatch.fnmatch(env.conf, pat):
                return True
    return False


# --- git identity per alias --------------------------------------------------------------------

def git_run(env, *args, cwd=None):
    """Runs git with HOME pointing at env.home so --global lands in the right place. (rc, stdout)."""
    sub_env = dict(os.environ, HOME=env.home)
    if not env.real_home:
        sub_env.pop("XDG_CONFIG_HOME", None)
        sub_env.pop("GIT_CONFIG_GLOBAL", None)
    try:
        r = subprocess.run(["git", *args], env=sub_env, cwd=cwd, capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.TimeoutExpired):
        return None, ""
    return r.returncode, r.stdout


def git_supports_hasconfig(env):
    rc, out = git_run(env, "--version")
    m = re.search(r"(\d+)\.(\d+)", out or "")
    if rc is None or not m:
        return None
    return (int(m.group(1)), int(m.group(2))) >= (2, 36)


def url_patterns(host):
    """Remote URL globs that mean "cloned through this alias", for includeIf hasconfig.
    git matches them with pathname semantics: `*` never crosses a `/`, and `**` only does so as a
    whole path component. Hence `alias:*/**` for org/repo and `alias:*` for a flat repo name."""
    pats = []
    for word in host["alias"].split():
        prefixes = [f"{host['user']}@{word}", word] if host["user"] else [word]
        for p in prefixes:
            pats += [f"{p}:*/**", f"{p}:*", f"ssh://{p}/**"]
    return pats


def identity_file(env, host):
    return os.path.join(env.git_dir, slug(host["alias"]) + ".gitconfig")


def signing_spec(host):
    return host["signing_key"] or host["key"]


def signing_pub(env, host, keys):
    """`keytype blob` of the host's signing key: what the agent offers now, else the .pub on disk; None if neither."""
    spec = signing_spec(host)
    found = match_key(spec, keys) if keys else []
    if len(found) == 1:
        return f"{found[0][0]} {found[0][1]}"
    local = read_pub(os.path.join(env.pub_dir, slug(spec) + ".pub"))
    return f"{local[0]} {local[1]}" if local else None


def resolve_signing(env, host, keys):
    """({"key": pub line, "program": signer}, None) for a signing host, or (None, why) when it cannot sign yet."""
    if not host["sign"]:
        return None, None
    program = signer_path()
    if not program:
        return None, f"op-ssh-sign not found (expected at {signer_candidates()[0]}); signing settings skipped"
    pub = signing_pub(env, host, keys)
    if not pub:
        return None, f"signing key '{signing_spec(host)}' is not offered by the agent and has no .pub; signing settings skipped"
    return {"key": pub, "program": program}, None


def render_identity(env, host, signing=None):
    out = [f"{GENERATED_MARK} from {env.tilde(env.registry)}; do not edit by hand (re-run install)",
           "[user]", f"\temail = {host['email']}"]
    if host["name"]:
        out.append(f"\tname = {host['name']}")
    if signing:
        out += [f"\tsigningkey = {signing['key']}",
                "[gpg]", "\tformat = ssh",
                '[gpg "ssh"]', f"\tprogram = {signing['program']}",
                f"\tallowedSignersFile = {env.tilde(env.allowed_signers)}"]
        if host["sign"] == "always":
            out += ["[commit]", "\tgpgsign = true", "[tag]", "\tgpgsign = true"]
    return "\n".join(out) + "\n"


def render_allowed_signers(env, hosts, keys):
    """allowed_signers content (one `<email> namespaces="git" <key>` line per signing identity), or None."""
    lines = []
    for h in hosts:
        pub = signing_pub(env, h, keys) if h["sign"] else None
        if pub:
            line = f'{h["email"]} namespaces="git" {pub}'
            if line not in lines:
                lines.append(line)
    if not lines:
        return None
    header = f"{GENERATED_MARK} from {env.tilde(env.registry)}; do not edit by hand (re-run install)"
    return header + "\n" + "\n".join(lines) + "\n"


def wanted_includes(env, hosts):
    """{condition: identity file} for every host with an email."""
    wanted = {}
    for h in hosts:
        if h["email"]:
            for p in url_patterns(h):
                wanted[f"hasconfig:remote.*.url:{p}"] = identity_file(env, h)
    return wanted


def current_includes(env):
    """{condition: path} of the global includeIf entries that point into our git dir; None if git fails."""
    rc, out = git_run(env, "config", "--global", "-z", "--get-regexp", r"^includeif\..*\.path$")
    if rc not in (0, 1):
        return None
    found = {}
    for entry in out.split("\0"):
        if "\n" not in entry:
            continue
        key, value = entry.split("\n", 1)
        cond = key[len("includeif."):-len(".path")]
        if os.path.abspath(os.path.expanduser(value)).startswith(env.git_dir + os.sep):
            found[cond] = value
    return found


def sync_allowed_signers(env, hosts, keys):
    content = render_allowed_signers(env, hosts, keys)
    if content:
        write_text(env, env.allowed_signers, content, 0o644, show=env.dry)
    elif os.path.exists(env.allowed_signers) and is_ours(env.allowed_signers):
        say(f"  remove {env.tilde(env.allowed_signers)} (no host signs any more)")
        if not env.dry:
            os.remove(env.allowed_signers)


def sync_git_identities(env, hosts, keys):
    wanted = wanted_includes(env, hosts)
    support = git_supports_hasconfig(env)
    if support is None:
        say("  WARN   git not found; identities skipped")
        return
    if not support:
        say("  WARN   git < 2.36 has no includeIf hasconfig; identities skipped")
        return
    current = current_includes(env)
    if current is None:
        say("  WARN   could not read the global git config; identities skipped")
        return
    sync_allowed_signers(env, hosts, keys)
    if not wanted and not current:
        say("  skip   no email: in the registry")
        return
    for h in hosts:
        if h["email"]:
            signing, why = resolve_signing(env, h, keys)
            if why:
                say(f"  WARN   {h['alias']}: {why}")
            write_text(env, identity_file(env, h), render_identity(env, h, signing), 0o600, show=env.dry)
    for cond, path in wanted.items():
        if current.get(cond) == path:
            continue
        say(f"  set    git includeIf \"{cond}\" -> {env.tilde(path)}")
        if not env.dry:
            git_run(env, "config", "--global", "--replace-all", f"includeIf.{cond}.path", path)
    for cond in current:
        if cond not in wanted:
            say(f"  unset  git includeIf \"{cond}\"")
            if not env.dry:
                git_run(env, "config", "--global", "--unset-all", f"includeIf.{cond}.path")
    if os.path.isdir(env.git_dir):
        for name in sorted(os.listdir(env.git_dir)):
            path = os.path.join(env.git_dir, name)
            if name.endswith(".gitconfig") and path not in wanted.values():
                say(f"  remove {env.tilde(path)} (alias no longer has an email)")
                if not env.dry:
                    os.remove(path)
    if wanted and all(current.get(c) == p for c, p in wanted.items()):
        say(f"  ok     git identities for {len(set(wanted.values()))} alias(es) (no changes)")


PROBE_KEYS = ("user.email", "user.name", "user.signingkey", "gpg.format", "gpg.ssh.program", "commit.gpgsign")


def probe_identity(env, host):
    """Clones nothing: a throwaway repo whose remote uses the alias, then asks git how it would commit there.
    Returns {config key: value} for PROBE_KEYS (missing keys -> ""), or None if git init fails."""
    import tempfile
    user = f"{host['user']}@" if host["user"] else ""
    url = f"{user}{host['alias'].split()[0]}:probe/probe.git"
    with tempfile.TemporaryDirectory() as tmp:
        rc, _ = git_run(env, "init", "-q", cwd=tmp)
        if rc != 0:
            return None
        git_run(env, "remote", "add", "origin", url, cwd=tmp)
        probe = {}
        for key in PROBE_KEYS:
            _rc, value = git_run(env, "config", "--get", key, cwd=tmp)
            probe[key] = (value or "").strip()
    return probe


# --- file writing ------------------------------------------------------------------------------

def read_text(path):
    """File content, or None if it does not exist. Other errors (permissions) propagate."""
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    except FileNotFoundError:
        return None
    except NotADirectoryError:
        return None


def write_text(env, path, content, mode, backup=False, show=False):
    """Writes only if the content differs. Returns True if (it would have) changed."""
    try:
        old = read_text(path)
    except OSError as e:
        say(f"  WARN   cannot read {env.tilde(path)} ({e.strerror}); not touching it")
        return False
    if old == content:
        _chmod(env, path, mode)
        say(f"  ok     {env.tilde(path)} (no changes)")
        return False
    verb = "update" if old is not None else "create"
    say(f"  {verb:6} {env.tilde(path)}")
    if show:
        for line in content.rstrip("\n").splitlines():
            say(f"         | {line}")
    if env.dry:
        return True
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if backup and old is not None:
        bak = f"{path}.bak.{time.strftime('%Y%m%d%H%M%S')}"
        shutil.copy2(path, bak)
        say(f"         backup: {env.tilde(bak)}")
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(content)
    os.chmod(tmp, mode)
    os.replace(tmp, path)
    return True


def _chmod(env, path, mode):
    if env.dry or not os.path.exists(path):
        return
    if stat.S_IMODE(os.stat(path).st_mode) != mode:
        os.chmod(path, mode)
        say(f"  chmod  {env.tilde(path)} -> {oct(mode)}")


# --- install -----------------------------------------------------------------------------------

def cmd_install(env):
    say(f"ssh-1password install (home: {env.home}{', dry-run: nothing is modified' if env.dry else ''})")

    say("1. 1Password")
    if not app_installed():
        say("  skip   1Password is not installed on this machine; nothing to do")
        return 0
    say("  ok     1Password app found")
    status, keys = agent_keys(env)
    if status == "ok":
        say(f"  ok     SSH agent reachable at {env.sock_tilde} ({len(keys)} key(s) offered)")
    elif status == "empty":
        say(f"  ok     SSH agent reachable at {env.sock_tilde}, but it offers no keys (check agent.toml / your vaults)")
    elif status == "timeout":
        say("  WARN   ssh-add did not answer: unlock 1Password (or authorize the pending request) and re-run")
    elif status == "no-ssh-add":
        say("  WARN   ssh-add not found: install OpenSSH client tools")
    else:
        say(f"  WARN   SSH agent not reachable at {env.sock_tilde}")
        say("         enable 1Password -> Settings -> Developer -> \"Use the SSH agent\", then re-run install")
        say("         (continuing: the generated config is harmless without the agent)")

    say("2. registry")
    source = env.registry
    if not os.path.isfile(env.registry):
        say(f"  create {env.tilde(env.registry)} (from templates/hosts.yml)")
        if env.dry:
            source = TEMPLATE
        else:
            os.makedirs(os.path.dirname(env.registry), exist_ok=True)
            shutil.copy(TEMPLATE, env.registry)
    else:
        say(f"  ok     {env.tilde(env.registry)}")
    hosts, problems = load_registry(source)
    hosts = hosts or []
    for p in problems:
        say(f"  WARN   {p}")
    if not hosts:
        say(f"  WARN   no hosts registered yet: edit {env.tilde(env.registry)} and re-run install")
    else:
        say(f"  ok     {len(hosts)} host(s), {len(distinct_keys(hosts))} key(s)")

    say("3. public keys from the agent")
    for spec, _vault in distinct_keys(hosts):
        pub = os.path.join(env.pub_dir, slug(spec) + ".pub")
        found = match_key(spec, keys) if status == "ok" else []
        if status != "ok":
            say(f"  skip   {spec}: agent not available" + (" (keeping existing .pub)" if os.path.exists(pub) else ""))
        elif len(found) == 1:
            t, blob, comment = found[0]
            write_text(env, pub, f"{t} {blob} {comment}\n".replace(" \n", "\n"), 0o644)
        elif not found:
            hint = "add vault: to the registry and re-run" if not spec.startswith("SHA256:") else "check the fingerprint"
            say(f"  WARN   {spec}: the agent does not offer it (renamed? in a vault outside Personal/Private/Employee? {hint})")
        else:
            say(f"  WARN   {spec}: {len(found)} items share this title in 1Password; rename one or use its SHA256: fingerprint")

    say("4. ssh config")
    write_text(env, env.conf, render_conf(env, hosts), 0o600, show=env.dry)
    if include_present(env):
        say(f"  ok     {env.tilde(env.config)} already includes {CONF_REL}")
    else:
        old = read_text(env.config) or ""
        new = (old.rstrip("\n") + "\n" + INCLUDE_BLOCK) if old.strip() else INCLUDE_BLOCK.lstrip("\n")
        write_text(env, env.config, new, 0o600, backup=True, show=env.dry)
    _chmod(env, env.ssh_dir, 0o700)

    say("5. agent.toml (which keys the agent offers, and in which order)")
    toml = render_agent_toml(env, hosts)
    if not hosts:
        say("  skip   no keys registered; an empty agent.toml would hide every key")
    elif toml is None:
        say("  WARN   every registered key is a SHA256: fingerprint; agent.toml needs item titles, so it is not written (an empty allowlist would hide every key)")
    elif os.path.exists(env.agent_toml) and not is_ours(env.agent_toml):
        existing = read_text(env.agent_toml) or ""
        missing = [s for s, _v in distinct_keys(hosts) if not s.startswith("SHA256:") and f'"{s}"' not in existing]
        if missing:
            say(f"  WARN   {env.tilde(env.agent_toml)} is yours; these keys are not listed in it, add them by hand:")
            for s in missing:
                say(f'         [[ssh-keys]]\n         item = "{s}"')
        else:
            say(f"  ok     {env.tilde(env.agent_toml)} is yours and lists every registered key")
    else:
        created = not os.path.exists(env.agent_toml)
        if write_text(env, env.agent_toml, toml, 0o600, show=env.dry) and created:
            say("         new file: lock and unlock 1Password once so the agent picks it up")

    say("6. git identity and commit signing per alias (includeIf hasconfig:remote.*.url)")
    sync_git_identities(env, hosts, keys if status == "ok" else [])
    if any(h["sign"] for h in hosts):
        say("         signing: upload the .pub to GitHub/GitLab as a *Signing key* (not only Authentication) and approve 'git' in 1Password on first use")

    say("Next: ssh-1password.py doctor   ·   test: ssh -T git@<alias>")
    return 0


# --- doctor ------------------------------------------------------------------------------------

class Report:
    def __init__(self):
        self.fails = 0

    def ok(self, msg):
        say(f"  OK   {msg}")

    def warn(self, msg):
        say(f"  WARN {msg}")

    def fail(self, msg):
        say(f"  FAIL {msg}")
        self.fails += 1


def ssh_resolved(alias, config):
    """`ssh -G alias` -> {option: [values]}; None if ssh is missing or fails."""
    try:
        r = subprocess.run(["ssh", "-G", "-F", config, alias], capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if r.returncode != 0:
        return None
    out = {}
    for line in r.stdout.splitlines():
        parts = line.split(None, 1)
        if parts:
            out.setdefault(parts[0], []).append(parts[1] if len(parts) > 1 else "")
    return out


def cmd_doctor(env):
    rep = Report()
    say(f"ssh-1password doctor (home: {env.home})")

    say("1Password")
    if app_installed():
        rep.ok("1Password app installed")
    else:
        rep.fail("1Password app not found (install it, then run install)")
    status, keys = agent_keys(env)
    if status in ("ok", "empty"):
        rep.ok(f"SSH agent reachable at {env.sock_tilde} ({len(keys)} key(s) offered)")
    elif status == "timeout":
        rep.warn("ssh-add did not answer: 1Password locked or a request is pending in its tray icon")
    else:
        rep.warn(f"SSH agent not reachable at {env.sock_tilde}: enable Settings -> Developer -> Use the SSH agent (or 1Password is closed)")

    say("registry")
    hosts, problems = load_registry(env.registry)
    if hosts is None:
        rep.fail(f"{env.tilde(env.registry)} does not exist (run install)")
        hosts, problems = [], []
    elif not hosts:
        rep.warn(f"{env.tilde(env.registry)} has no hosts yet (edit it, then run install)")
    else:
        rep.ok(f"{env.tilde(env.registry)}: {len(hosts)} host(s), {len(distinct_keys(hosts))} key(s)")
    for p in problems:
        rep.warn(p)

    say("ssh config")
    if include_present(env):
        rep.ok(f"{env.tilde(env.config)} includes {CONF_REL}")
    else:
        rep.fail(f"{env.tilde(env.config)} does not include {CONF_REL} (run install)")
    try:
        current = read_text(env.conf)
    except OSError as e:
        current = None
        rep.warn(f"cannot read {env.tilde(env.conf)} ({e.strerror})")
    if current is None:
        rep.fail(f"{env.tilde(env.conf)} missing (run install)")
    elif current != render_conf(env, hosts):
        rep.fail(f"{env.tilde(env.conf)} is out of date with the registry (run install)")
    else:
        rep.ok(f"{env.tilde(env.conf)} matches the registry")
    for path in (env.config, env.conf):
        if os.path.exists(path) and stat.S_IMODE(os.stat(path).st_mode) & 0o077:
            rep.warn(f"{env.tilde(path)} is readable by others (chmod 600)")
    if os.path.isdir(env.ssh_dir) and stat.S_IMODE(os.stat(env.ssh_dir).st_mode) & 0o077:
        rep.warn(f"{env.tilde(env.ssh_dir)} is accessible by others (chmod 700)")

    say("keys")
    expected_pubs = set()
    for spec, _vault in distinct_keys(hosts):
        pub = os.path.join(env.pub_dir, slug(spec) + ".pub")
        expected_pubs.add(os.path.basename(pub))
        local = read_pub(pub)
        if local is None:
            rep.fail(f"{spec}: {env.tilde(pub)} missing (run install with 1Password unlocked)")
            continue
        if status != "ok":
            rep.warn(f"{spec}: {env.tilde(pub)} present; agent not available to confirm it")
            continue
        if any(k[1] == local[1] for k in keys):
            rep.ok(f"{spec}: {env.tilde(pub)} offered by the agent ({fingerprint(local[1])})")
        elif match_key(spec, keys):
            rep.warn(f"{spec}: the agent offers a different key under this title; run install to refresh the .pub")
        else:
            rep.warn(f"{spec}: not offered by the agent (renamed, deleted, or its vault is not in agent.toml)")
    if os.path.isdir(env.pub_dir):
        for name in sorted(os.listdir(env.pub_dir)):
            if name.endswith(".pub") and name not in expected_pubs:
                rep.warn(f"orphan {env.tilde(os.path.join(env.pub_dir, name))}: not in the registry (delete it)")

    say("hosts")
    if not env.real_home:
        rep.warn("ssh -G checks skipped (--home differs from the real home: ssh expands ~ itself)")
    for h in hosts:
        alias = h["alias"].split()[0]
        if not env.real_home:
            break
        res = ssh_resolved(alias, env.config)
        if res is None:
            rep.fail(f"{alias}: ssh -G failed (syntax error in ssh config?)")
            continue
        want_pub = os.path.join(env.ssh_dir, PUB_DIR_REL, slug(h["key"]) + ".pub")
        files = [os.path.expanduser(f) for f in res.get("identityfile", [])]
        agent = os.path.expanduser(res.get("identityagent", [""])[0].strip('"'))
        problems = []
        if want_pub not in files:
            problems.append(f"identityfile is {files} (an earlier entry in your config overrides it)")
        elif len(files) > 1:
            problems.append(f"extra IdentityFile entries also apply: {files}")
        if res.get("identitiesonly", [""])[0] != "yes":
            problems.append("identitiesonly is not yes")
        if agent != env.sock:
            problems.append(f"identityagent is '{agent}' instead of the 1Password socket")
        if res.get("forwardagent", [""])[0] == "yes":
            problems.append("forwardagent is yes")
        if problems:
            rep.fail(f"{alias}: " + "; ".join(problems))
        else:
            rep.ok(f"{alias} -> {h['user'] + '@' if h['user'] else ''}{h['hostname'] or alias}, key {h['key']}")

    say("agent.toml")
    if not hosts:
        rep.warn("no keys registered; agent.toml not checked")
    elif not os.path.exists(env.agent_toml):
        rep.warn(f"{env.tilde(env.agent_toml)} missing: the agent offers every key in your default vaults (install creates it)")
    else:
        text = read_text(env.agent_toml) or ""
        missing = [s for s, _v in distinct_keys(hosts) if not s.startswith("SHA256:") and f'"{s}"' not in text]
        owner = "generated" if is_ours(env.agent_toml) else "yours"
        if missing:
            rep.warn(f"{env.tilde(env.agent_toml)} ({owner}) does not list: {', '.join(missing)}")
        else:
            rep.ok(f"{env.tilde(env.agent_toml)} ({owner}) lists every registered key")

    say("git identity")
    with_email = [h for h in hosts if h["email"]]
    if not with_email:
        rep.ok("no email: in the registry (git identity not managed)")
    elif not git_supports_hasconfig(env):
        rep.warn("git missing or older than 2.36: includeIf hasconfig unavailable, identities not applied")
    else:
        current = current_includes(env) or {}
        wanted = wanted_includes(env, hosts)
        missing = [c for c, p in wanted.items() if current.get(c) != p]
        if missing:
            rep.fail(f"{len(missing)} includeIf entr{'y is' if len(missing) == 1 else 'ies are'} missing in the global git config (run install)")
        agent_now = keys if status == "ok" else []
        allowed = read_text(env.allowed_signers) or ""
        for h in with_email:
            alias, path = h["alias"], identity_file(env, h)
            signing, why = resolve_signing(env, h, agent_now)
            if why:
                rep.fail(f"{alias}: {why}")
                continue
            on_disk = read_text(path)
            if on_disk != render_identity(env, h, signing):
                if signing and on_disk and "signingkey = " in on_disk and signing["key"] not in on_disk:
                    rep.fail(f"{alias}: the signing key changed in 1Password; {env.tilde(path)} holds the old one "
                             "(run install, then upload the new .pub to GitHub/GitLab as a Signing key)")
                else:
                    rep.fail(f"{alias}: {env.tilde(path)} missing or out of date (run install)")
                continue
            probe = probe_identity(env, h)
            if probe is None:
                rep.warn(f"{alias}: could not probe (git init failed)")
                continue
            if probe["user.email"] != h["email"] or (h["name"] and probe["user.name"] != h["name"]):
                rep.fail(f"{alias}: a repo with this remote would commit as '{probe['user.name']} <{probe['user.email']}>' instead of the registry identity")
                continue
            if not signing:
                rep.ok(f"{alias}: repos cloned through this alias commit as <{h['email']}>")
                continue
            wrong = []
            if probe["gpg.format"] != "ssh":
                wrong.append(f"gpg.format is '{probe['gpg.format']}'")
            if probe["user.signingkey"] != signing["key"]:
                wrong.append("user.signingkey is not the key the agent offers")
            if probe["gpg.ssh.program"] != signing["program"]:
                wrong.append(f"gpg.ssh.program is '{probe['gpg.ssh.program']}'")
            want_gpgsign = "true" if h["sign"] == "always" else ""
            if probe["commit.gpgsign"] != want_gpgsign:
                wrong.append(f"commit.gpgsign is '{probe['commit.gpgsign']}' (sign: {h['sign']})")
            if f'{h["email"]} namespaces="git" {signing["key"]}' not in allowed:
                wrong.append(f"{env.tilde(env.allowed_signers)} lacks this identity (run install)")
            if wrong:
                rep.fail(f"{alias}: " + "; ".join(wrong))
            else:
                rep.ok(f"{alias}: commits as <{h['email']}>, signs with '{signing_spec(h)}' ({h['sign']})")

    say("")
    if rep.fails == 0:
        say("doctor: all good")
        return 0
    say(f"doctor: {rep.fails} problem(s)")
    return 1


# --- main --------------------------------------------------------------------------------------

def main(argv):
    cmd, dry, registry, home = None, False, None, os.path.expanduser("~")
    args = list(argv)
    while args:
        a = args.pop(0)
        if a in ("install", "doctor"):
            cmd = a
        elif a == "--dry-run":
            dry = True
        elif a in ("-f", "--file") and args:
            registry = os.path.expanduser(args.pop(0))
        elif a.startswith("--file="):
            registry = os.path.expanduser(a.split("=", 1)[1])
        elif a == "--home" and args:
            home = os.path.expanduser(args.pop(0))
        elif a.startswith("--home="):
            home = os.path.expanduser(a.split("=", 1)[1])
        elif a in ("-h", "--help"):
            print(__doc__.strip())
            return 0
        else:
            print(f"ssh-1password: unknown argument: {a}", file=sys.stderr)
            return 2
    if cmd is None:
        print(__doc__.strip().splitlines()[0], file=sys.stderr)
        print("usage: ssh-1password.py install|doctor [--dry-run] [--file <hosts.yml>] [--home <dir>]", file=sys.stderr)
        return 2
    env = Env(home, registry, dry)
    return cmd_install(env) if cmd == "install" else cmd_doctor(env)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
